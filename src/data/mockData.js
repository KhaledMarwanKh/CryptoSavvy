// ==========================================
// Helper functions
// ==========================================

export function getSymbolData(symbol) {
  return cryptoMarketData.find((item) => item.symbol === symbol);
}

function intervalToMs(interval) {
  const map = {
    "1m": 60 * 1000,
    "3m": 3 * 60 * 1000,
    "5m": 5 * 60 * 1000,
    "15m": 15 * 60 * 1000,
    "30m": 30 * 60 * 1000,
    "1h": 60 * 60 * 1000,
    "2h": 2 * 60 * 60 * 1000,
    "4h": 4 * 60 * 60 * 1000,
    "6h": 6 * 60 * 60 * 1000,
    "12h": 12 * 60 * 60 * 1000,
    "1d": 24 * 60 * 60 * 1000,
    "1w": 7 * 24 * 60 * 60 * 1000,
  };

  if (!map[interval]) {
    throw new Error(`Unsupported interval: ${interval}`);
  }

  return map[interval];
}

function randomBetween(min, max) {
  return Math.random() * (max - min) + min;
}

function roundByPrice(value, price) {
  if (price >= 1000) return Number(value.toFixed(2));
  if (price >= 1) return Number(value.toFixed(4));
  return Number(value.toFixed(6));
}

// ==========================================
// 2) Function to generate candles chart data
// ==========================================

export function generateCandlesChartData(symbol, interval = "1m", count = 100) {
  const market = getSymbolData(symbol);

  if (!market) {
    throw new Error(`Symbol not found: ${symbol}`);
  }

  const intervalMs = intervalToMs(interval);
  const now = Date.now();
  const candles = [];

  let lastClose = market.price;
  const volatility = market.price * 0.01;

  for (let i = count - 1; i >= 0; i--) {
    const openTime = now - i * intervalMs;
    const open = lastClose;

    const move = randomBetween(-volatility, volatility);
    const close = open + move;

    const high = Math.max(open, close) + randomBetween(0, volatility * 0.5);
    const low = Math.min(open, close) - randomBetween(0, volatility * 0.5);
    const volume = randomBetween(
      market.volume * 0.00001,
      market.volume * 0.0001,
    );

    candles.push({
      openTime,
      open: roundByPrice(open, market.price),
      high: roundByPrice(high, market.price),
      low: roundByPrice(low, market.price),
      close: roundByPrice(close, market.price),
      volume: Number(volume.toFixed(2)),
      closeTime: openTime + intervalMs - 1,
    });

    lastClose = close;
  }

  return candles;
}

// ==========================================
// 3) Function to generate orderbook data
// ==========================================

export function generateOrderBook(symbol, levels = 20) {
  const market = getSymbolData(symbol);

  if (!market) {
    throw new Error(`Symbol not found: ${symbol}`);
  }

  const midPrice = market.price;
  const spread = midPrice * 0.0005;
  const asks = [];
  const bids = [];

  for (let i = 0; i < levels; i++) {
    const askPrice = midPrice + spread + i * (midPrice * 0.0003);
    const bidPrice = midPrice - spread - i * (midPrice * 0.0003);

    const askQty = randomBetween(0.1, 25);
    const bidQty = randomBetween(0.1, 25);

    asks.push({
      price: roundByPrice(askPrice, midPrice),
      quantity: Number(askQty.toFixed(4)),
      total: Number((askPrice * askQty).toFixed(2)),
    });

    bids.push({
      price: roundByPrice(bidPrice, midPrice),
      quantity: Number(bidQty.toFixed(4)),
      total: Number((bidPrice * bidQty).toFixed(2)),
    });
  }

  asks.sort((a, b) => a.price - b.price);
  bids.sort((a, b) => b.price - a.price);

  return {
    symbol,
    timestamp: Date.now(),
    asks,
    bids,
  };
}

// ==========================================
// 4) Function to generate a single candle
// ==========================================

export function generateCandle(
  symbol,
  lastClose = null,
  timestamp = Date.now(),
) {
  const market = getSymbolData(symbol);

  if (!market) {
    throw new Error(`Symbol not found: ${symbol}`);
  }

  const basePrice = lastClose ?? market.price;
  const volatility = basePrice * 0.01;

  const open = basePrice;
  const close = open + randomBetween(-volatility, volatility);
  const high = Math.max(open, close) + randomBetween(0, volatility * 0.5);
  const low = Math.min(open, close) - randomBetween(0, volatility * 0.5);
  const volume = randomBetween(market.volume * 0.00001, market.volume * 0.0001);

  return {
    time: timestamp,
    open: roundByPrice(open, market.price),
    high: roundByPrice(high, market.price),
    low: roundByPrice(low, market.price),
    close: roundByPrice(close, market.price),
    volume: Number(volume.toFixed(2)),
  };
}

